from llm.ollama_client import chat


def write_chapter(context):
    # =====================================
    # 基础信息
    # =====================================
    novel_title = context.config["novel"]["title"]
    target = context.target
    latest_chapter_id = target["latest_chapter_id"]
    novel_state = context.novel_state
    # =====================================
    # Planning
    # =====================================
    plan = context.current_plan
    volume_plan = plan.get("volume", {})
    arc_plan = plan.get("arc", {})
    before_plots = plan.get("before_plots", {})
    current_plot = plan.get("current_plot", {})
    after_plots = plan.get("after_plots", {})
    related_characters = context.related_characters
    # =====================================
    # Memory
    # =====================================
    volume_memory = context.volume_memory
    arc_memory = context.arc_memory
    plot_memory = context.plot_memory
    chapter_memory = context.chapter_memory
    # =====================================
    # Knowledge
    # =====================================
    knowledge = context.knowledge
    chapter_history = context.chapter_history
    prompt = f"""
你是一名专业的长篇网络小说作者。
你的任务：
继续创作小说：
《{novel_title}》
当前章节：
{latest_chapter_id}
================================================
【最高原则】
================================================
你不是重新创作。
你是在一个已经连载中的小说世界继续写作。
必须遵守：
1. 已发生历史不可修改
2. 人物性格不可修改
3. 世界规则不可修改
4. 力量体系不可修改
5. 时间线不可修改
6. 不提前完成未来剧情
7. 不跳跃剧情阶段
如果发生冲突：
Memory > Planning > 创作自由
================================================
【小说信息】
================================================
小说：
{context.config["novel"]}
================================================
【Knowledge 世界知识库】
================================================
以下内容属于世界底层规则。
必须严格遵守：
{knowledge}
================================================
【Planning 剧情规划】
================================================
未来剧情规划：
-------------------------------
Volume（卷）
-------------------------------
{volume_plan}
-------------------------------
Arc（剧情弧）
-------------------------------
{arc_plan}
-------------------------------
Plot（剧情节点）
-------------------------------
{current_plot}
================================================
【附近剧情规划】
================================================
以下是当前 Plot 之前的剧情。
作用：
- 保持剧情方向
- 保持剧情连贯
- 避免重复写之前的剧情
{before_plots}
================================================
【附近剧情规划】
================================================
以下是当前 Plot 之后的剧情。
作用：
- 保持剧情方向
- 避免提前写完
- 保留伏笔
{after_plots}
================================================
【Memory 历史记忆】
================================================
以下内容是真实发生过的历史。
禁止修改。
-------------------------------
Volume Memory
-------------------------------
{volume_memory}
-------------------------------
Arc Memory
-------------------------------
{arc_memory}
-------------------------------
Plot Memory
-------------------------------
{plot_memory}
-------------------------------
Chapter Memory
-------------------------------
最近章节发生事件：
{chapter_memory}
================================================
【当前人物状态】
================================================
小说状态：
{novel_state}
人物状态：
{related_characters}
================================================
【最近正文】
================================================
以下正文用于保持：
- 文风
- 节奏
- 人物语言
不要复制。
{chapter_history}
================================================
【创作任务】
================================================
现在开始创作：
{latest_chapter_id}
本章必须：
1.
完成 Chapter Goal
2.
推进当前 Plot
3.
服务 Arc 主线
4.
符合 Volume 大方向
5.
留下合理伏笔
6.
不能提前解决未来核心冲突
================================================
【章节质量】
================================================
必须包含：
✓ 环境描写
✓ 人物对白
✓ 心理描写
✓ 冲突
✓ 剧情推进
✓ 世界观展示
✓ 人物成长
✓ 章节结尾悬念
================================================
【输出】
================================================
只输出小说正文。
禁止：
- JSON
- Markdown
- 解释
- 分析
- 作者说明
长度：
4000字
保持网络小说阅读体验。
"""
    return chat(prompt)
