from llm.ollama_client import chat


def write_chapter(context):

    # ==================================================
    # 基础信息
    # ==================================================

    config = context.config

    novel_title = config["novel"]["title"]

    task = context.task

    target = task["target"]

    chapter_id = target["chapter"]

    # ==================================================
    # Planning Tree
    # ==================================================

    planning = context.current_plan

    volume_plan = planning.get("volume", {})

    arc_plan = planning.get("arc", {})

    plot_plan = planning.get("plot", {})

    chapter_plan = planning.get("chapter", {})

    scene_plan = planning.get("scenes", [])

    # ==================================================
    # Related Plot
    # ==================================================

    related_plots = context.related_plots

    # ==================================================
    # Memory Tree
    # ==================================================

    volume_memory = context.volume_memory

    arc_memory = getattr(context, "arc_memory", {})

    plot_memory = context.plot_memory

    chapter_memory = context.chapter_memory

    # ==================================================
    # Knowledge
    # ==================================================

    knowledge = context.knowledge

    # ==================================================
    # State
    # ==================================================

    protagonist = context.novel_state.get("protagonist", {})

    chapter_history = context.chapter_history

    # ==================================================
    # Prompt
    # ==================================================

    prompt = f"""


你是一名专业的长篇网络小说作者。


你的任务：

继续创作小说：

《{novel_title}》


当前章节：

{chapter_id}



==================================================
【最高优先级规则】
==================================================


你正在创作一本已经连载中的小说。

必须保证：

1. 世界观连续
2. 人物连续
3. 力量体系连续
4. 时间线连续
5. 剧情连续


任何情况下：

历史 Memory > Planning


如果发现：

Planning 与 Memory 冲突

必须修改 Planning。

不能修改已经发生的历史。


==================================================
【Knowledge 世界知识库】
==================================================


以下内容定义小说世界。


包括：

- 世界规则
- 力量体系
- 人物设定
- 势力关系


禁止违反：


{knowledge}



==================================================
【Future Planning 未来剧情规划】
==================================================


这是未来剧情方向。


=========================
Volume
=========================

{volume_plan}



=========================
Arc
=========================

{arc_plan}



=========================
Plot
=========================

{plot_plan}



=========================
Chapter Goal
=========================


当前章节必须完成：

{chapter_plan}



=========================
Scene Plan
=========================


当前章节场景规划：


{scene_plan}



==================================================
【附近剧情规划】
==================================================


用于理解：

前因：

后果：

不要跳跃。


{related_plots}



==================================================
【Memory 历史记忆】
==================================================


以下全部是真实发生事件。


禁止修改。


=========================
小说长期记忆
=========================

{story_memory}



=========================
Volume Memory
=========================

{volume_memory}



=========================
Arc Memory
=========================

{arc_memory}



=========================
Plot Memory
=========================

{plot_memory}



=========================
Chapter Memory
=========================

{chapter_memory}



==================================================
【当前人物状态】
==================================================


主角：

{protagonist}



==================================================
【最近正文】
==================================================


保持：

- 文风
- 节奏
- 人物语言


不要复制。


{chapter_history}



==================================================
【创作任务】
==================================================


开始创作：

{chapter_id}



必须完成：


1. 完成 Chapter Goal

2. 推进 Plot

3. 服务 Arc

4. 服务 Volume


禁止：


1. 提前完成未来剧情

2. 修改历史事件

3. 强行升级

4. 引入未规划的重要设定

5. 改变人物性格



==================================================
【章节质量】
==================================================


章节需要包含：


- 环境描写

- 人物对白

- 心理描写

- 冲突

- 剧情推进

- 伏笔


结尾留下下一章动力。



==================================================
【输出】
==================================================


只输出小说正文。


禁止：

JSON

Markdown

解释

分析

作者说明



字数：

3000-5000字



"""

    return chat(prompt)
